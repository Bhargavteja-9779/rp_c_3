#!/usr/bin/env python3
"""Build the Online Resources (electronic supplementary material) from the committed sources.

  Online_Resource_1.docx/.pdf  derivations (Propositions 1-4)
  Online_Resource_2.docx/.pdf  pre-registered protocol with amendments and post-hoc changes,
                               leakage audit (Table S1)
  Online_Resource_3.xlsx       per-dataset results and supplementary tables S2-S9
"""
import subprocess
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CODE = ROOT / "code"
SUP = ROOT / "supplementary"
OUT = SUP / "online_resources"
REF = HERE / "reference_springer.docx"
TITLE = ("Shift-aware probabilities for random convolutional kernel time series classifiers via "
         "leverage-moderated leave-one-out calibration")


def pandoc(md_text, name):
    tmp = OUT / f"_{name}.md"
    tmp.write_text(md_text)
    dst = OUT / f"{name}.docx"
    subprocess.run(["pandoc", str(tmp), "-o", str(dst), f"--reference-doc={REF}"], check=True)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", str(OUT), str(dst)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    tmp.unlink()


def md_table(df):
    cols = list(df.columns)
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    rows += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def resource_1():
    txt = (SUP / "derivations.md").read_text()
    pandoc(f"**Online Resource 1** to: *{TITLE}*\n\n" + txt, "Online_Resource_1")


def resource_2():
    txt = (SUP / "experimental_design_preregistration.md").read_text()
    la = pd.read_csv(CODE / "results" / "leakage_audit.csv")
    dup = la[(la.test_in_train > 0) | (la.dup_within_train > 0) | (la.dup_within_test > 0)]
    s1 = ("\n\n## Table S1. Leakage audit of the official UCR splits\n\n"
          f"Exact duplicate series within and across the official splits for the {len(la)} datasets; only "
          f"datasets with at least one duplicate are listed ({len(dup)} datasets; "
          f"{int((la.test_in_train > 0).sum())} with test series that duplicate a training series). "
          "The full table is `code/results/leakage_audit.csv`.\n\n" + md_table(dup))
    pandoc(f"**Online Resource 2** to: *{TITLE}*\n\n" + txt + s1, "Online_Resource_2")


def resource_3():
    raw = pd.read_csv(CODE / "results" / "raw_results.csv",
                      usecols=["dataset", "resample", "transform", "train_frac", "method", "cond", "sev",
                               "nll", "brier", "ece", "acc", "shift_auroc", "coverage", "set_size"])
    main = raw[(raw["transform"].isin(["minirocket", "raw"])) & (raw["train_frac"] == 1.0)]
    per = lambda d: (d.groupby(["dataset", "method", "resample"])[["nll", "brier", "ece", "acc", "shift_auroc"]]
                     .mean().groupby(["dataset", "method"]).mean().round(4).reset_index())
    sheets = {
        "S2 clean per dataset": per(main[main["cond"] == "clean"]),
        "S3 corrupted per dataset": per(main[main["cond"] != "clean"]),
    }
    tab = CODE / "tables"
    for sheet, f in [("S4 training-set size", "table_train_size.csv"),
                     ("S5 other extractors", "table_generalisation_extractors.csv"),
                     ("S6 by corruption family", "table_robustness_by_family.csv"),
                     ("S7 natural shift", "table_natural_shift_tasks.csv"),
                     ("S8 conformal", "table_conformal.csv"),
                     ("S9 efficiency", "table_efficiency.csv"),
                     ("S11 triage case study", "table_case_study_datasets.csv")]:
        if (tab / f).exists():
            sheets[sheet] = pd.read_csv(tab / f)
    lr = CODE / "results" / "check_logreg_convergence.json"
    if lr.exists():
        sheets["S10 LogReg convergence"] = pd.read_json(lr)
    readme = pd.DataFrame({"Online Resource 3": [
        f"Supplementary tables to: {TITLE}",
        "S2/S3: per-dataset metrics (mean over resamples; S3 also over the 18 corruption conditions) for every method.",
        "S4: training-set size experiment (Table S4 of the manuscript). S5: MultiRocket and Hydra features.",
        "S6: medians over datasets per corruption family and severity. S7: natural cross-axis shift per task.",
        "S8: conformal prediction sets. S9: computational cost. S10: logistic-regression convergence check.",
        "S11: triage case study per dataset (stream = 30 % faulty recordings; budgets 10/20/30 %).",
        "All values are machine-generated by run_all.py; per-condition values are in code/results/raw_results.csv."]})
    with pd.ExcelWriter(OUT / "Online_Resource_3.xlsx") as xw:
        readme.to_excel(xw, sheet_name="README", index=False)
        for k, v in sheets.items():
            v.to_excel(xw, sheet_name=k[:31], index=False)


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True, parents=True)
    resource_1(); resource_2(); resource_3()
    print("written", sorted(p.name for p in OUT.iterdir()))
