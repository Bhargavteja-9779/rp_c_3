"""loom-triage: command-line triage of time series recordings with a human review queue.

    loom-triage fit --train train.csv --model model.pkl            # first column = label
    loom-triage run --model model.pkl --input new.csv --budget 0.2 --out queue.csv --report report.html
    loom-triage evaluate --model model.pkl --test test.csv          # labelled data: accuracy, NLL, triage

CSV files contain one recording per row (comma, tab or whitespace separated, no header). In the
training and test files the first column is the class label. An HTML report summarises the run.
"""
import argparse
import html
import sys
from pathlib import Path

import numpy as np


def _read(path, labelled):
    import pandas as pd
    df = pd.read_csv(path, header=None, sep=None, engine="python")
    if labelled:
        return df.iloc[:, 1:].to_numpy(float), df.iloc[:, 0].to_numpy()
    return df.to_numpy(float), None


def _svg_hist(conf, review, width=520, height=150, bins=20):
    """Inline SVG histogram of confidences, review-queue part highlighted."""
    edges = np.linspace(0, 1, bins + 1)
    ha, _ = np.histogram(conf[~review], edges); hr, _ = np.histogram(conf[review], edges)
    top = max(1, (ha + hr).max()); bw = width / bins
    bars = []
    for i in range(bins):
        x = i * bw
        hA = height * ha[i] / top; hR = height * hr[i] / top
        bars.append(f'<rect x="{x + 1:.1f}" y="{height - hR:.1f}" width="{bw - 2:.1f}" height="{hR:.1f}" fill="#d9682b"/>')
        bars.append(f'<rect x="{x + 1:.1f}" y="{height - hR - hA:.1f}" width="{bw - 2:.1f}" height="{hA:.1f}" fill="#2a78d6"/>')
    return (f'<svg viewBox="0 0 {width} {height + 18}" width="100%" role="img" aria-label="confidence histogram">'
            + "".join(bars) + f'<text x="0" y="{height + 14}" font-size="11">confidence 0</text>'
            f'<text x="{width}" y="{height + 14}" font-size="11" text-anchor="end">1</text></svg>')


def _report(df, path, title):
    review = (df["decision"] == "review").to_numpy()
    rows = "".join(f"<tr><td>{i}</td><td>{html.escape(str(r.prediction))}</td><td>{r.confidence:.3f}</td>"
                   f"<td>{r.unusualness:.1f}</td></tr>"
                   for i, r in df[review].sort_values("confidence").head(50).iterrows())
    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title><style>
:root{{--bg:#fff;--fg:#1d1d1f;--mut:#6b6b70;--line:#e3e3e8}}
@media (prefers-color-scheme:dark){{:root{{--bg:#151517;--fg:#ececf0;--mut:#a0a0a8;--line:#2c2c31}}}}
body{{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;max-width:760px;margin:24px auto;padding:0 16px}}
.k{{display:flex;gap:24px;flex-wrap:wrap}}.k div{{border:1px solid var(--line);border-radius:8px;padding:10px 14px}}
.k b{{display:block;font-size:22px}}table{{border-collapse:collapse;width:100%}}td,th{{border-bottom:1px solid var(--line);padding:4px 8px;text-align:left}}
small{{color:var(--mut)}}</style></head><body>
<h1>{html.escape(title)}</h1>
<div class="k"><div><b>{len(df)}</b>recordings</div><div><b>{int((~review).sum())}</b>decided automatically</div>
<div><b>{int(review.sum())}</b>sent to review</div><div><b>{df['confidence'][~review].min() if (~review).any() else float('nan'):.2f}</b>lowest automatic confidence</div></div>
<h2>Confidence</h2>{_svg_hist(df['confidence'].to_numpy(), review)}
<small>Blue: decided automatically. Orange: review queue.</small>
<h2>Review queue (least confident first, up to 50)</h2>
<table><tr><th>row</th><th>prediction</th><th>confidence</th><th>unusualness (h/h<sub>ref</sub>)</th></tr>{rows}</table>
<p><small>Unusualness above about 3 means the recording lies far from the training data, for example
because of noise, drift, spikes or missing samples. Generated by loom-triage.</small></p></body></html>"""
    Path(path).write_text(doc)


def main(argv=None):
    from . import LOOMClassifier
    ap = argparse.ArgumentParser(prog="loom-triage", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fit", help="train a model on labelled recordings")
    f.add_argument("--train", required=True); f.add_argument("--model", required=True)
    f.add_argument("--transform", default="minirocket"); f.add_argument("--seed", type=int, default=0)
    r = sub.add_parser("run", help="triage new recordings")
    r.add_argument("--model", required=True); r.add_argument("--input", required=True)
    r.add_argument("--budget", type=float, default=0.2); r.add_argument("--threshold", type=float)
    r.add_argument("--alpha", type=float, help="add jackknife+ prediction sets at this miscoverage")
    r.add_argument("--out", required=True); r.add_argument("--report")
    e = sub.add_parser("evaluate", help="evaluate on labelled recordings")
    e.add_argument("--model", required=True); e.add_argument("--test", required=True)
    e.add_argument("--budget", type=float, default=0.2)
    a = ap.parse_args(argv)
    if a.cmd == "fit":
        X, y = _read(a.train, True)
        clf = LOOMClassifier(transform=a.transform, random_state=a.seed).fit(X, y)
        clf.save(a.model)
        print(f"trained on {len(y)} recordings, {len(clf.classes_)} classes, length {X.shape[1]} -> {a.model}")
    elif a.cmd == "run":
        clf = LOOMClassifier.load(a.model)
        X, _ = _read(a.input, False)
        df = clf.triage(X, budget=a.budget, threshold=a.threshold, alpha=a.alpha)
        df.to_csv(a.out, index_label="row")
        if a.report:
            _report(df, a.report, f"Triage report: {Path(a.input).name}")
        print(f"{len(df)} recordings: {(df.decision == 'auto').sum()} automatic, {(df.decision == 'review').sum()} for review -> {a.out}")
    else:
        from .evaluation.metrics import nll
        clf = LOOMClassifier.load(a.model)
        X, y = _read(a.test, True)
        P = clf.predict_proba(X); yi = np.searchsorted(clf.classes_, y)
        df = clf.triage(X, budget=a.budget); auto = (df.decision == "auto").to_numpy()
        ok = P.argmax(1) == yi
        print(f"accuracy {ok.mean():.3f}  NLL {nll(P, yi):.3f}  "
              f"error of automatic decisions at {a.budget:.0%} review: {(~ok[auto]).mean():.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
